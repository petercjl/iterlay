import { URL } from "node:url";
import console from "node:console";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const read = (file) => readFile(new URL(file, root), "utf8");
const pkg = JSON.parse(await read("package.json"));
const caps = JSON.parse(await read("capabilities.json"));
assert.equal(pkg.name, "@petercjl/tuda");
assert.equal(pkg.version, caps.version);
assert((await read("skills/using-tuda/SKILL.md")).includes(`version: "${pkg.version}"`));
for (const name of ["dist/main.js", "dist/board-plugin.js", "dist/board-plugin.LICENSES.txt", "LICENSE", "THIRD_PARTY_NOTICES.md", "INSTALL.md", "UPDATE.md"]) await read(name);
assert.equal(pkg.tudaRelease, undefined, "Plugin packages must not bind desktop releases");
assert(!pkg.files.includes("release-manifest.json"), "Desktop manifests belong to the desktop package");
console.log(JSON.stringify({ ok: true, package: pkg.name, version: pkg.version, desktopReleasePresent: false }));
